import { Router } from 'express';
import { PrismaClient } from '@prisma/client';
const prisma = new PrismaClient();
import { logShadowAudit } from './shadowLogger';

const router = Router();

// Cuentas Bancarias
router.get('/:condominioId/cuentas', async (req, res) => {
  try {
    const cuentas = await prisma.cuentaBancaria.findMany({
      where: { condominioId: req.params.condominioId }
    });
    res.json(cuentas);
  } catch (error) {
    res.status(500).json({ error: 'Error' });
  }
});

router.post('/:condominioId/cuentas', async (req, res) => {
  try {
    const { nombre, tipo, saldoUSD, saldoVES } = req.body;
    const cuenta = await prisma.cuentaBancaria.create({
      data: {
        condominioId: req.params.condominioId,
        nombre, tipo, saldoUSD: Number(saldoUSD), saldoVES: Number(saldoVES)
      }
    });
    res.json(cuenta);
  } catch (error) {
    res.status(500).json({ error: 'Error' });
  }
});

